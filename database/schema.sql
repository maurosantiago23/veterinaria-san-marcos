-- 1. Limpieza de tablas existentes en orden de dependencia
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE DETALLE_BOLETA CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE BOLETA CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE PRODUCTO CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE CATEGORIA CASCADE CONSTRAINTS';
   EXECUTE IMMEDIATE 'DROP TABLE USUARIO CASCADE CONSTRAINTS';
EXCEPTION
   WHEN OTHERS THEN NULL;
END;
/

-- 2. Tabla USUARIO (Manejo de credenciales y roles exigidos por la pauta)
CREATE TABLE USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    telefono VARCHAR2(20),
    rol VARCHAR2(20) DEFAULT 'CLIENTE' CHECK (rol IN ('ADMIN', 'VENDEDOR', 'CLIENTE'))
);

-- 3. Tabla CATEGORIA (Servicios Medicos, Farmacia Clinica, Alimentos)
CREATE TABLE CATEGORIA (
    id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(50) NOT NULL UNIQUE
);

-- 4. Tabla PRODUCTO (Catalogo e inventario clinico)
CREATE TABLE PRODUCTO (
    id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(30) NOT NULL UNIQUE,
    nombre VARCHAR2(150) NOT NULL,
    descripcion VARCHAR2(500),
    precio NUMBER(10, 2) NOT NULL,
    stock NUMBER NOT NULL CHECK (stock >= 0),
    imagen_url VARCHAR2(255),
    id_categoria NUMBER NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id_categoria)
);

-- 5. Tabla BOLETA (Encabezado de venta asociada al cliente autenticado)
CREATE TABLE BOLETA (
    id_boleta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_orden VARCHAR2(50) NOT NULL UNIQUE,
    fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    subtotal NUMBER(10, 2) NOT NULL,
    iva NUMBER(10, 2) NOT NULL,
    total NUMBER(10, 2) NOT NULL,
    estado_pago VARCHAR2(20) DEFAULT 'APROBADO' CHECK (estado_pago IN ('APROBADO', 'RECHAZADO', 'PENDIENTE')),
    id_usuario NUMBER NOT NULL,
    CONSTRAINT fk_boleta_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario)
);

-- 6. Tabla DETALLE_BOLETA (Lineas de detalle de la compra)
CREATE TABLE DETALLE_BOLETA (
    id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_boleta NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMBER(10, 2) NOT NULL,
    subtotal_linea NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_detalle_boleta FOREIGN KEY (id_boleta) REFERENCES BOLETA(id_boleta) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES PRODUCTO(id_producto)
);

